#!/usr/bin/env python3
"""Tables for the data lines (vbi20.c): PAL teletext page P100 and NTSC closed-caption shapes.
Writes firmware/main/vbi20_tables.h.

Teletext (625-line system B): 6.9375 Mbit/s NRZ, LSB first, 45 bytes per line (clock run-in
0x55 0x55, framing code 0x27, 2 address bytes, 40 data bytes); 0 = black, 1 = 66 % of white
(462 mV). At 20 MS/s a bit is 320/111 samples, so each sample is a sum of the 5 nearest bit
pulses: ttx_lut[phase][5 bits]. The pulse is a raised cosine spectrum with 50 % roll-off
(zero above 5.2 MHz, inside the PAL video band).

Closed captions (EIA-608, NTSC line 21): 32 fH = 503 kbit/s; 50 IRE = 1, blanking = 0. Clock
run-in 10.5 us after 0H, start bit at 27.38 us, 16 data bits. Edges are raised-cosine ramps.

The page comes from data/TEST25 (a raw 40 x 25 teletext page, TEST25 from
https://mdfs.net/System/Teletext/Samples/). Its row 0 is replaced by our own header.
usage: make_vbi20.py [page file]
"""
import os
import sys

import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
page_file = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'data', 'TEST25')
dst = os.path.join(here, '..', 'firmware', 'main', 'vbi20_tables.h')

LSB_MV = 5.0
IRE_MV = 714.3 / 100

# --- teletext packets ---------------------------------------------------------------------------
HAM = [0x15, 0x02, 0x49, 0x5E, 0x64, 0x73, 0x38, 0x2F, 0xD0, 0xC7, 0x8C, 0x9B, 0xA1, 0xB6, 0xFD, 0xEA]


def par(c):                     # 7-bit character with odd parity in bit 7
    c &= 0x7F
    return c | (0x80 if bin(c).count('1') % 2 == 0 else 0)


MAG = 1                         # magazine 1, page 00 -> P100


def packet(row, payload):
    p = [0x55, 0x55, 0x27, HAM[(MAG & 7) | (row & 1) << 3], HAM[row >> 1]] + payload
    assert len(p) == 45
    return p


def header_text():
    # 32 displayed characters (columns 8..39): text, then the clock hh:mm:ss in the last 8
    t = b'\x83ESP32 FuBK \x87P100 \x82'.ljust(24) + b'00:00:00'
    assert len(t) == 32
    return t


def packets(page):
    hdr = [HAM[0]] * 8          # page 00, subcode 0, control bits 0 (parallel, English)
    out = [packet(0, hdr + [par(c) for c in header_text()])]
    for r in range(1, 25):
        out.append(packet(r, [par(c) for c in page[r * 40:(r + 1) * 40]]))
    return out


TTX_CLOCK_OFS = 5 + 8 + 24      # byte of the first clock digit in packet 0

# --- teletext pulse table -----------------------------------------------------------------------
TTX_MV = 462.0
TTX_PH = 32                     # phases per bit (bit = 320 steps of 1/111 sample: phase = step / 10)
TTX_BETA = 0.5


def rc_pulse(t, beta=TTX_BETA):
    """Raised-cosine pulse, t in bits, 1 at t = 0, 0 at the other bit centres."""
    t = np.asarray(t, float)
    den = 1 - (2 * beta * t) ** 2
    with np.errstate(divide='ignore', invalid='ignore'):
        h = np.sinc(t) * np.cos(np.pi * beta * t) / den
    h[np.abs(den) < 1e-9] = np.pi / 4 * np.sinc(1 / (2 * beta))
    return h


def ttx_lut():
    """ttx_lut[ph][b]: sample value (DAC steps above blanking) at phase ph of bit k, where
    b bit j (0..4) is the data bit k - 2 + j. Sample position in the bit: (ph * 10 + 5) / 320."""
    lut = np.zeros((TTX_PH, 32))
    for ph in range(TTX_PH):
        x = (ph * 10 + 5) / 320                 # position inside bit k (0 = its start)
        d = x - 0.5 - (np.arange(5) - 2)        # distance to the centre of bit k - 2 + j
        h = rc_pulse(d)
        for b in range(32):
            lut[ph, b] = TTX_MV / LSB_MV * sum(h[j] for j in range(5) if b >> j & 1)
    q = np.round(lut).astype(int)
    assert q.min() >= -128 and q.max() <= 127
    return q


# --- closed captions ----------------------------------------------------------------------------
CC_MV = 50 * IRE_MV
CC_RAMP = 8                     # samples per edge (400 ns, 10-90 % about 240 ns)


def cc_tables():
    """Run-in: 64 steps of one cycle of (1 - cos) / 2; edge: CC_RAMP steps of a raised-cosine
    rise. Both in DAC steps above blanking."""
    a = CC_MV / LSB_MV
    runin = np.round(a * (1 - np.cos(2 * np.pi * (np.arange(64) + 0.5) / 64)) / 2).astype(int)
    edge = np.round(a * (1 - np.cos(np.pi * (np.arange(CC_RAMP) + 0.5) / CC_RAMP)) / 2).astype(int)
    return runin, edge, int(round(a))


def main():
    page = open(page_file, 'rb').read()[:1000]
    assert len(page) == 1000
    pk = packets(page)
    lut = ttx_lut()
    runin, edge, cc_a = cc_tables()
    with open(dst, 'w') as f:
        f.write('// Generated by esp32/tools/make_vbi20.py. Do not edit.\n')
        f.write('// Teletext page P100 from TEST25 (https://mdfs.net/System/Teletext/Samples/), own header.\n')
        f.write('#pragma once\n#include <stdint.h>\n')
        f.write(f'#define TTX_PACKETS 25\n#define TTX_CLOCK_OFS {TTX_CLOCK_OFS}\n#define TTX_PH {TTX_PH}\n')
        f.write(f'#define CC_RAMP {CC_RAMP}\n#define CC_A {cc_a}\n')
        f.write('static const uint8_t VBI_ATTR ttx_page[TTX_PACKETS][45] = {\n')
        for p in pk:
            f.write('    {' + ','.join('0x%02X' % b for b in p) + '},\n')
        f.write('};\n')
        f.write('// teletext sample (DAC steps above blanking): [phase in the bit][bits k-2 .. k+2]\n')
        f.write(f'static const int8_t VBI_ATTR ttx_lut[TTX_PH][32] = {{\n')
        for row in lut:
            f.write('    {' + ','.join(str(v) for v in row) + '},\n')
        f.write('};\n')
        f.write('static const uint8_t VBI_ATTR cc_runin[64] = {' + ','.join(str(v) for v in runin) + '};\n')
        f.write('static const uint8_t VBI_ATTR cc_edge[CC_RAMP] = {' + ','.join(str(v) for v in edge) + '};\n')
    print(f'wrote {dst}: {len(pk)} packets, ttx_lut {lut.min()}..{lut.max()}, CC {cc_a} steps')


if __name__ == '__main__':
    main()
